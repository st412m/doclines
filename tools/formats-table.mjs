#!/usr/bin/env node
// The formats table of README.md, built from FORMATS (src/formats.js). The table sits
// between the two marker comments below; test/readme.test.js fails when it differs.
//
//   node tools/formats-table.mjs           print the table
//   node tools/formats-table.mjs --write   replace the table in README.md
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { FORMATS } from '../src/index.js';

export const README = new URL('../README.md', import.meta.url);
export const START = '<!-- formats-table:start (generated by tools/formats-table.mjs) -->';
export const END = '<!-- formats-table:end -->';

export function formatsTable(formats = FORMATS) {
  const rows = formats.map((f) => `| \`${f.id}\` | ${f.label} | ${f.family} | ${f.extensions.map((e) => `\`${e}\``).join(' ')} | ${f.textOnDisk ? 'yes' : 'no'} |`);
  return ['| id | Label | Family | Extensions | Text on disk |', '|---|---|---|---|---|', ...rows].join('\n');
}

/** The table currently between the markers of `readme`, or null without markers. */
export function tableIn(readme) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) return null;
  return readme.slice(a + START.length, b).replace(/\r/g, '').trim();
}

function write() {
  const readme = fs.readFileSync(README, 'utf8');
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md: markers ${START} … ${END} not found`);
  const next = `${readme.slice(0, a + START.length)}\n${formatsTable()}\n${readme.slice(b)}`;
  if (next !== readme) fs.writeFileSync(README, next);
  return next !== readme;
}

function isMain() {
  try {
    return import.meta.url === pathToFileURL(fs.realpathSync(process.argv[1])).href;
  } catch {
    return false;
  }
}

if (isMain()) {
  if (process.argv.includes('--write')) console.log(write() ? 'README.md: formats table updated' : 'README.md: formats table up to date');
  else console.log(formatsTable());
}
